  var api = {
    compile: compile,
    tint: tint,
    rows: ROWS,

    // night=true 时描边用夜色
    get: function (name, night) {
      var key = name + (night ? '@n' : '@d');
      if (cache[key]) return cache[key];

      // 优先用图集 sprite（笔触与地面统一）
      var at = ATLAS_SPRITE[name];
      if (at && B.atlas && B.atlas.has(at[0])) {
        var cut = B.atlas.slice(at[0], at[1]);
        if (cut) {
          var e0 = { base: cut, w: cut.width, h: cut.height, fromAtlas: true };
          e0.flash = tint(cut, '#ffffff');
          cache[key] = e0;
          return e0;
        }
      }

      var rows = overrides[name] || ROWS[name];
      if (!rows) return null;
      var map = MAPS[name];
      if (!map) return null;
      var base = compile(rows, map, night ? B.pal.outline.night : B.pal.outline.day);
      var entry = { base: base, w: base.width, h: base.height };
      if (FLASHABLE[name]) entry.flash = tint(base, '#ffffff');
      cache[key] = entry;
      return entry;
    },

    // 运行时覆盖矩阵（美术追加或改色）
    setRows: function (name, rows, map) {
      overrides[name] = rows;
      if (map) MAPS[name] = map;
      api.clearCache();
    },

    // 图集 sprite 在 atlas 加载完之前会被缓存成空，加载完要清一次
    rebindAtlas: function () { api.clearCache(); },

    clearCache: function () { cache = {}; }
  };

  B.sprites = api;
